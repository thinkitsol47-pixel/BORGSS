import { cn } from "@/lib/utils";

/**
 * Loading placeholder. Used by route-level loading.tsx files so a page's
 * shape appears immediately instead of a blank screen.
 */
export function Skeleton({
  className,
  ...props
}: React.HTMLAttributes<HTMLDivElement>) {
  return (
    <div
      aria-hidden
      className={cn("animate-pulse rounded-md bg-brand-tint", className)}
      {...props}
    />
  );
}

/** A few lines of fake text; the last line is short, as real text tends to be. */
export function SkeletonText({
  lines = 3,
  className,
}: {
  lines?: number;
  className?: string;
}) {
  return (
    <div className={cn("space-y-2", className)}>
      {Array.from({ length: lines }, (_, i) => (
        <Skeleton
          key={i}
          className={cn("h-3.5", i === lines - 1 ? "w-2/3" : "w-full")}
        />
      ))}
    </div>
  );
}
